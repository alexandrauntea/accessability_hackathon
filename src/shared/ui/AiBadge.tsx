import React from 'react';
import { View } from 'react-native';
import { AppText } from './AppText';

/** Transparency: every AI-generated block shows this label (+ why, when given). */
export function AiBadge({ why }: { why?: string }) {
  return (
    <View accessible accessibilityLabel={`Generated by AI. ${why ?? ''} Please check it before acting.`}>
      <AppText variant="muted">AI-generated{why ? ` · ${why}` : ''} · check before acting</AppText>
    </View>
  );
}
