import React from 'react';
import { View } from 'react-native';
import { Ionicons } from '@expo/vector-icons';
import { AppText } from './AppText';
import { useTheme } from '../theme/ThemeProvider';
import { space } from '../theme/tokens';

/** Transparency: every AI-generated block shows this label (+ why, when given). */
export function AiBadge({ why }: { why?: string }) {
  const { c, radius } = useTheme();
  return (
    <View
      accessible
      accessibilityRole="text"
      accessibilityLabel={`Generated by AI. ${why ?? ''} Please check it before acting.`}
      style={{
        flexDirection: 'row',
        alignItems: 'center',
        alignSelf: 'flex-start',
        gap: space.xs,
        paddingHorizontal: space.sm,
        paddingVertical: space.xs,
        borderRadius: radius.pill,
        backgroundColor: c.accentSoft,
        borderWidth: 1,
        borderColor: c.border,
      }}
    >
      <Ionicons name="sparkles-outline" size={14} color={c.accent} />
      <AppText variant="small" style={{ color: c.onAccentSoft, fontWeight: '700' }}>
        AI-generated{why ? ` · ${why}` : ''}
      </AppText>
    </View>
  );
}